def find_knowledge(question):
    """根据题目找到最相关的知识点"""
    # 按关键词长度排序，优先匹配更具体的关键词
    matches = []
    for topic, knowledge in KNOWLEDGE.items():
        if topic in question:
            matches.append((len(topic), topic, knowledge))
    matches.sort(reverse=True)
    if matches:
        return matches[0][1], matches[0][2]
    return None, None

def get_kb_link(question):
    for topic, title in KB_LINKS.items():
        if topic in question:
            return title
    return None

def generate_rich_explanation(key, q):
    """生成有实际知识点的解释"""
    qtype = q['type']
    question = q['question']
    answer = q['answer']

    # 找到相关知识点
    topic, knowledge = find_knowledge(question)

    if qtype == 'j':
        return generate_judge_exp(question, answer, topic, knowledge)
    elif qtype == 's':
        return generate_single_exp(question, answer, q.get('options', {}), topic, knowledge)
    elif qtype == 'm':
        return generate_multi_exp(question, answer, q.get('options', {}), topic, knowledge)

def generate_judge_exp(question, answer, topic, knowledge):
    """判断题：答案+知识点+为什么"""
    if answer == True or answer == '正确':
        marker = '✅ 正确。'
    else:
        marker = '❌ 错误。'

    # 构建解释
    exp = marker

    if knowledge:
        # 有知识点：先给知识点，再解释题目
        exp += knowledge
        # 如果答案是错误的，说明正确的说法
        if answer == False or answer == '错误':
            # 尝试从题目中提取正确说法
            if '不' in question:
                correct = question.replace('。', '').replace('不需要', '需要').replace('不能', '能').replace('不是', '是').replace('不会', '会').replace('无需', '需要').replace('不包括', '包括')
                exp += f'因此，正确表述应为：{correct}。'
            elif '不存在' in question:
                exp += '因此，该说法不正确，相关概念是存在的。'
    else:
        # 没有匹配的知识点：生成基本解释
        if answer == False or answer == '错误':
            if '不' in question:
                correct = question.replace('。', '').replace('不需要', '需要').replace('不能', '能').replace('不是', '是').replace('不会', '会').replace('无需', '需要')
                exp += f'{question.replace("。", "")}，这一说法不正确。正确表述：{correct}。'
            else:
                exp += f'{question.replace("。", "")}，这一说法不正确。'
        else:
            exp += f'{question.replace("。", "")}，这一说法正确。'

    # 添加知识库链接
    kb = get_kb_link(question)
    if kb:
        exp += f' [🔗 {kb}]'

    return exp

def generate_single_exp(question, answer, options, topic, knowledge):
    """单选题：正确答案+知识点+逐选项分析"""
    if not options:
        exp = f'正确答案是{answer}。'
        if knowledge:
            exp += knowledge
        return exp

    correct_text = options.get(answer, '')
    exp = f'正确答案是{answer}（{correct_text}）。'

    # 添加知识点
    if knowledge:
        exp += knowledge

    # 逐选项分析
    for opt_key in sorted(options.keys()):
        opt_text = options[opt_key]
        if opt_key == answer:
            exp += f'{opt_key}（{opt_text}）正确。'
        else:
            exp += f'{opt_key}（{opt_text}）不正确。'

    # 知识库链接
    kb = get_kb_link(question)
    if kb:
        exp += f' [🔗 {kb}]'

    return exp

def generate_multi_exp(question, answer, options, topic, knowledge):
    """多选题：正确答案+知识点+逐选项分析"""
    if not options or not isinstance(answer, list):
        exp = f'正确答案是{answer}。'
        if knowledge:
            exp += knowledge
        return exp

    correct_keys = [k for k in sorted(options.keys()) if k in answer]
    ans_str = '、'.join(correct_keys)
    exp = f'正确答案是{ans_str}。'

    # 添加知识点
    if knowledge:
        exp += knowledge

    # 逐选项分析
    for opt_key in sorted(options.keys()):
        opt_text = options[opt_key]
        if opt_key in answer:
            exp += f'{opt_key}（{opt_text}）✓应选。'
        else:
            exp += f'{opt_key}（{opt_text}）✗不选。'

    # 知识库链接
    kb = get_kb_link(question)
    if kb:
        exp += f' [🔗 {kb}]'

    return exp


